"""The four agent routes. Each one is a specific user action; the agents never call each other.

  GET  /api/plan                 the generated weekly plan (code only, no AI)
  POST /api/programs/recommend   the plan + the Program Architect's explanation
  POST /api/workouts/build       Workout Builder
  POST /api/calendar/{id}/custom Workout Builder, saved onto that calendar day (app/calendar.py has the rules)
  GET  /api/coach/summary        Coach (dashboard load)
  POST /api/basics/ask           Fitness Basics (red-flag pre-filter runs first)

Security: the user is ALWAYS the one in the sign-in token (token_user_id). No route accepts a user_id
from the URL, query, or body, and the request bodies forbid extra fields, so nothing the user types (or a
model outputs) can point an agent at someone else's data.

Pregnant / postpartum users (needs_clinical_review) never reach a model: the Program Architect and Basics
answer from code, and the Workout Builder and Coach return 403 pointing to /pregnancy-support.

Every agent call is logged to agent_runs with measured token counts (app/agents/harness.py: run_logged).
"""

from fastapi import APIRouter, Depends, HTTPException
from pydantic import BaseModel
from pydantic_ai.exceptions import ModelHTTPError, UnexpectedModelBehavior, UsageLimitExceeded

from app import calendar
from app.agents import basics, coach, program_architect, workout_builder
from app.agents.harness import AgentUnavailable
from app.db import connect
from app.safety_rules import CLINICAL_REVIEW_NO_AI, CLINICAL_REVIEW_PAGE, profile_needs_clinical_review
from app.security import token_user_id
from app.services.program_generator import NoProfile, generate_for_user

router = APIRouter(prefix="/api")

AI_FAILED = "The AI helper couldn't finish that just now. Please try again in a moment."


class NoBody(BaseModel):
    model_config = {"extra": "forbid"}   # an empty body is fine; {"user_id": 2} is rejected


def signed_in_user(uid: int = Depends(token_user_id)) -> int:
    """The user from the token, and only if the account still exists."""
    conn = connect()
    try:
        if not conn.execute("SELECT 1 FROM users WHERE id = ?", (uid,)).fetchone():
            raise HTTPException(401, "Your sign-in is invalid or expired. Please sign in again.")
    finally:
        conn.close()
    return uid


def no_ai_for_clinical_review(uid: int = Depends(signed_in_user)) -> int:
    """Pregnant / postpartum users never reach an AI agent (shared_rules.md rule 6). Checked in code before
    the agent runs, so the model is never called and no tokens are spent."""
    if profile_needs_clinical_review(uid):
        raise HTTPException(403, {"code": "needs_clinical_review", "message": CLINICAL_REVIEW_NO_AI,
                                  "page": CLINICAL_REVIEW_PAGE})
    return uid


async def _run(coro):
    try:
        output, meta = await coro
    except AgentUnavailable as e:
        raise HTTPException(503, str(e)) from e
    except (UsageLimitExceeded, UnexpectedModelBehavior, ModelHTTPError) as e:
        raise HTTPException(502, AI_FAILED) from e
    return {"result": output.model_dump(), "meta": meta}


@router.get("/plan")
def weekly_plan(uid: int = Depends(signed_in_user)) -> dict:
    """The user's weekly plan, generated by code from their quiz (no model call, no tokens)."""
    try:
        return generate_for_user(uid).model_dump()
    except NoProfile as e:
        raise HTTPException(409, str(e)) from e


@router.post("/programs/recommend")
async def recommend_program(body: NoBody | None = None, uid: int = Depends(signed_in_user)) -> dict:
    try:
        return await _run(program_architect.recommend_plan(uid, route="POST /api/programs/recommend"))
    except NoProfile as e:
        raise HTTPException(409, str(e)) from e


@router.post("/workouts/build")
async def build_workout(body: workout_builder.WorkoutRequest, uid: int = Depends(no_ai_for_clinical_review)) -> dict:
    return await _run(workout_builder.build_workout(uid, body, route="POST /api/workouts/build"))


@router.post("/calendar/{entry_id}/custom")
async def build_custom_day(entry_id: int, body: workout_builder.WorkoutRequest,
                           uid: int = Depends(no_ai_for_clinical_review)) -> dict:
    """Override one calendar day with a custom workout. The same Workout Builder and injury filter as
    /workouts/build; the day is checked before the model runs (an ineligible day costs no tokens)."""
    calendar.check_overridable(uid, entry_id)
    out = await _run(workout_builder.build_workout(uid, body, route="POST /api/calendar/{id}/custom"))
    entry = calendar.apply_custom(uid, entry_id, out["result"], body.model_dump())
    return {**out, "entry": entry}


@router.get("/coach/summary")
async def coach_summary(uid: int = Depends(no_ai_for_clinical_review)) -> dict:
    return await _run(coach.coach_summary(uid, route="GET /api/coach/summary"))


@router.post("/basics/ask")
async def ask_basics(body: basics.BasicsQuestion, uid: int = Depends(signed_in_user)) -> dict:
    # The red-flag safety check still runs for everyone; for pregnant / postpartum users the AI step is skipped.
    return await _run(basics.answer_question(uid, body.question, route="POST /api/basics/ask",
                                             clinical_review=profile_needs_clinical_review(uid)))
