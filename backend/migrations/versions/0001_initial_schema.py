"""The Bee Fit schema, ported from SQLite (backend/app/db/schema.sql as of 2026-10-25) to Postgres.

Same tables, columns, CHECKs and foreign keys as the SQLite version, so the code and the data mean exactly what they
did. Differences are only in how Postgres spells things:
  * JSON columns stay TEXT holding JSON (the code reads and writes JSON text), checked with IS JSON / IS JSON OBJECT /
    IS JSON ARRAY instead of json_valid() / json_type().
  * Dates stay ISO TEXT ('YYYY-MM-DD'), checked with a regex instead of GLOB; timestamps default to UTC ISO text.
  * usernames are CITEXT: unique and matched without regard to case, like COLLATE NOCASE.
  * ids are identity columns (BY DEFAULT, so the one-time SQLite import can keep the old ids).
  * Foreign keys from user data to CONTENT tables (exercises, sources) are DEFERRABLE, so a content refresh can replace
    the content tables inside one transaction without touching anyone's data (app/db/seed.py).

Revision ID: 0001
Revises:
Create Date: 2026-10-25
"""

from alembic import op

revision = "0001"
down_revision = None
branch_labels = None
depends_on = None

NOW = """(to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'))"""
DATE_RE = "'^[0-9]{4}-[0-9]{2}-[0-9]{2}$'"
ID = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"

SCHEMA = f"""
CREATE EXTENSION IF NOT EXISTS citext;

-- ---------------------------------------------------------------- users
-- Deleting a user removes their data too (ON DELETE CASCADE, plus explicit deletes in app/users.py).
-- username and first_name identify the person, so neither ever reaches an agent (app/agents/context.py).
CREATE TABLE users (
    id            {ID},
    username      CITEXT NOT NULL UNIQUE,
    first_name    TEXT,
    password_hash TEXT NOT NULL,
    created_at    TEXT NOT NULL DEFAULT {NOW}
);

CREATE TABLE quiz_questions (
    id            TEXT PRIMARY KEY,
    order_index   INTEGER NOT NULL,
    prompt        TEXT NOT NULL,
    question_type TEXT NOT NULL CHECK (question_type IN ('multi_select', 'single_select', 'number', 'text', 'date')),
    options       TEXT NOT NULL DEFAULT '[]' CHECK (options IS JSON),
    settings      TEXT NOT NULL DEFAULT '{{}}' CHECK (settings IS JSON),
    required      INTEGER NOT NULL DEFAULT 1 CHECK (required IN (0, 1))
);

CREATE TABLE quiz_profiles (
    id                     {ID},
    user_id                BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    goal                   TEXT NOT NULL CHECK (goal IN ('stronger', 'lose_weight', 'feel_good')),
    injury_flags           TEXT NOT NULL DEFAULT '[]' CHECK (injury_flags IS JSON),
    experience_level       TEXT CHECK (experience_level IN ('beginner', 'intermediate', 'advanced')),
    equipment              TEXT NOT NULL DEFAULT '[]' CHECK (equipment IS JSON),
    pregnancy_status       TEXT CHECK (pregnancy_status IN ('none', 'pregnant', 'postpartum')),
    -- Computed by the database, so it can never disagree with pregnancy_status. No plan while this is 1.
    needs_clinical_review  INTEGER GENERATED ALWAYS AS
                               (CASE WHEN pregnancy_status IN ('pregnant', 'postpartum') THEN 1 ELSE 0 END) STORED,
    weight                 DOUBLE PRECISION CHECK (weight > 0),
    goal_weight            DOUBLE PRECISION CHECK (goal_weight > 0),
    consent_accepted       INTEGER NOT NULL CHECK (consent_accepted IN (0, 1)),
    consent_accepted_at    TEXT,
    consent_version        TEXT,
    calendar_mode          TEXT NOT NULL DEFAULT 'generated' CHECK (calendar_mode IN ('generated', 'review', 'self')),
    plan_reviewed          INTEGER NOT NULL DEFAULT 0 CHECK (plan_reviewed IN (0, 1)),
    plan_swaps             TEXT NOT NULL DEFAULT '{{}}' CHECK (plan_swaps IS JSON OBJECT),
    plan_started_on        TEXT,
    created_at             TEXT NOT NULL DEFAULT {NOW},
    updated_at             TEXT NOT NULL DEFAULT {NOW},
    CHECK (consent_accepted = 1 AND consent_accepted_at IS NOT NULL AND consent_version IS NOT NULL),
    CHECK (goal = 'lose_weight' OR (weight IS NULL AND goal_weight IS NULL))
);

-- ---------------------------------------------------------------- content (seeded from content/ by app/db/seed.py)
CREATE TABLE sources (
    id          TEXT PRIMARY KEY,
    order_index INTEGER NOT NULL,
    name        TEXT NOT NULL,
    url         TEXT,
    license     TEXT NOT NULL,
    used_for    TEXT NOT NULL,
    status      TEXT NOT NULL CHECK (status IN ('active', 'placeholder', 'pending'))
);

CREATE TABLE exercises (
    id                       TEXT PRIMARY KEY,
    name                     TEXT NOT NULL,
    muscle_group             TEXT NOT NULL CHECK (muscle_group IN ('legs', 'arms', 'chest', 'shoulders', 'back', 'core',
                                                                   'full_body')),
    equipment_needed         TEXT NOT NULL DEFAULT '["none"]' CHECK (equipment_needed IS JSON),
    difficulty               TEXT NOT NULL CHECK (difficulty IN ('beginner', 'intermediate', 'advanced')),
    force                    TEXT CHECK (force IS NULL OR force IN ('push', 'pull', 'static')),
    injury_contraindications TEXT NOT NULL DEFAULT '[]' CHECK (injury_contraindications IS JSON),
    -- An empty list on an 'untagged' exercise means "nobody has checked", NOT "safe for every injury".
    contraindication_status  TEXT NOT NULL CHECK (contraindication_status IN ('untagged', 'draft', 'pt_reviewed')),
    injury_rationale         TEXT NOT NULL DEFAULT '{{}}' CHECK (injury_rationale IS JSON OBJECT),
    demo_media_path          TEXT,
    media_type               TEXT CHECK (media_type IN ('image', 'gif', 'video')),
    instructions             TEXT NOT NULL,
    est_time_seconds         INTEGER NOT NULL CHECK (est_time_seconds > 0),
    category                 TEXT,
    primary_muscles          TEXT NOT NULL DEFAULT '[]' CHECK (primary_muscles IS JSON),
    secondary_muscles        TEXT NOT NULL DEFAULT '[]' CHECK (secondary_muscles IS JSON),
    source_dataset           TEXT NOT NULL REFERENCES sources(id) DEFERRABLE INITIALLY IMMEDIATE,
    citations                TEXT NOT NULL DEFAULT '[]' CHECK (citations IS JSON ARRAY),
    status                   TEXT NOT NULL DEFAULT 'placeholder' CHECK (status IN ('placeholder', 'pt_reviewed'))
);
CREATE INDEX idx_exercises_muscle_group ON exercises(muscle_group);
CREATE INDEX idx_exercises_source ON exercises(source_dataset);

CREATE TABLE goal_protocols (
    id                     {ID},
    goal                   TEXT NOT NULL CHECK (goal IN ('stronger', 'lose_weight', 'feel_good')),
    experience_level       TEXT NOT NULL CHECK (experience_level IN ('beginner', 'intermediate', 'advanced')),
    session_length_minutes INTEGER NOT NULL CHECK (session_length_minutes BETWEEN 15 AND 60),
    sets_range             TEXT NOT NULL,
    reps_range             TEXT NOT NULL,
    rest_seconds           INTEGER NOT NULL CHECK (rest_seconds BETWEEN 0 AND 300),
    progression_note       TEXT NOT NULL,
    reference_notes        TEXT,
    source_id              TEXT NOT NULL REFERENCES sources(id) DEFERRABLE INITIALLY IMMEDIATE,
    citations              TEXT NOT NULL DEFAULT '[]' CHECK (citations IS JSON ARRAY),
    status                 TEXT NOT NULL DEFAULT 'placeholder' CHECK (status IN ('placeholder', 'pt_reviewed')),
    UNIQUE (goal, experience_level)
);

-- ---------------------------------------------------------------- bookkeeping
-- key 'content_sha256': which content/ files the content tables were last seeded from (app/db/__init__.py).
CREATE TABLE app_meta (
    key   TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

-- ---------------------------------------------------------------- user activity
CREATE TABLE built_workouts (
    id          {ID},
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    request     TEXT NOT NULL CHECK (request IS JSON),
    session     TEXT NOT NULL CHECK (session IS JSON),
    created_at  TEXT NOT NULL DEFAULT {NOW}
);

CREATE TABLE cardio_logs (
    id               {ID},
    user_id          BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    date             TEXT NOT NULL CHECK (date ~ {DATE_RE}),
    activity         TEXT CHECK (activity IS NULL OR length(activity) <= 80),
    exercise_id      TEXT REFERENCES exercises(id) DEFERRABLE INITIALLY IMMEDIATE,
    cardio_type      TEXT,
    measure          TEXT NOT NULL DEFAULT 'duration' CHECK (measure IN ('duration', 'steps', 'distance')),
    duration_minutes INTEGER CHECK (duration_minutes BETWEEN 1 AND 600),
    steps            INTEGER CHECK (steps BETWEEN 1 AND 100000),
    distance_miles   DOUBLE PRECISION CHECK (distance_miles > 0 AND distance_miles <= 200),
    created_at       TEXT NOT NULL DEFAULT {NOW},
    CHECK (activity IS NOT NULL OR exercise_id IS NOT NULL),
    CHECK ((measure = 'duration') = (duration_minutes IS NOT NULL)),
    CHECK ((measure = 'steps') = (steps IS NOT NULL)),
    CHECK ((measure = 'distance') = (distance_miles IS NOT NULL))
);
CREATE INDEX idx_cardio_logs_user_date ON cardio_logs(user_id, date);

CREATE TABLE calendar_entries (
    id              {ID},
    user_id         BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    date            TEXT NOT NULL CHECK (date ~ {DATE_RE}),
    day_type        TEXT NOT NULL CHECK (day_type IN ('workout', 'rest', 'cardio')),
    workout_content TEXT NOT NULL DEFAULT '{{}}' CHECK (workout_content IS JSON OBJECT),
    completed       INTEGER NOT NULL DEFAULT 0 CHECK (completed IN (0, 1)),
    notes           TEXT,
    source          TEXT NOT NULL DEFAULT 'generated' CHECK (source IN ('generated', 'custom')),
    planned_content TEXT CHECK (planned_content IS NULL OR planned_content IS JSON),
    created_at      TEXT NOT NULL DEFAULT {NOW},
    updated_at      TEXT NOT NULL DEFAULT {NOW},
    UNIQUE (user_id, date),
    CHECK ((source = 'custom') = (planned_content IS NOT NULL))
);

CREATE TABLE workout_logs (
    id                {ID},
    user_id           BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    date              TEXT NOT NULL,
    exercise_id       TEXT REFERENCES exercises(id) DEFERRABLE INITIALLY IMMEDIATE,
    plan_day          TEXT CHECK (plan_day IN ('mon', 'tue', 'wed', 'thu', 'fri', 'sat', 'sun')),
    sets              INTEGER CHECK (sets >= 0),
    reps              INTEGER CHECK (reps >= 0),
    weight_used       DOUBLE PRECISION CHECK (weight_used >= 0),
    duration_seconds  INTEGER CHECK (duration_seconds >= 0),
    notes             TEXT,
    calendar_entry_id BIGINT REFERENCES calendar_entries(id) ON DELETE CASCADE,
    cardio_log_id     BIGINT REFERENCES cardio_logs(id) ON DELETE CASCADE
);
CREATE INDEX idx_workout_logs_user_date ON workout_logs(user_id, date);
CREATE INDEX idx_workout_logs_calendar ON workout_logs(calendar_entry_id);

CREATE TABLE exercise_favorites (
    id          {ID},
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    exercise_id TEXT NOT NULL REFERENCES exercises(id) DEFERRABLE INITIALLY IMMEDIATE,
    created_at  TEXT NOT NULL DEFAULT {NOW},
    UNIQUE (user_id, exercise_id)
);

CREATE TABLE measurements (
    id           {ID},
    user_id      BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    date         TEXT NOT NULL,
    body_weight  DOUBLE PRECISION CHECK (body_weight > 0),
    measurements TEXT NOT NULL DEFAULT '{{}}' CHECK (measurements IS JSON)
);
CREATE INDEX idx_measurements_user_date ON measurements(user_id, date);

-- ---------------------------------------------------------------- safety
CREATE TABLE safety_events (
    id           {ID},
    user_id      BIGINT REFERENCES users(id) ON DELETE CASCADE,
    timestamp    TEXT NOT NULL DEFAULT {NOW},
    source       TEXT NOT NULL CHECK (source IN ('quiz', 'basics_qa', 'calendar_note', 'cardio_log')),
    trigger_text TEXT NOT NULL,
    action_taken TEXT NOT NULL
);
CREATE INDEX idx_safety_events_time ON safety_events(timestamp);
CREATE INDEX idx_safety_events_source ON safety_events(source, timestamp);

-- ---------------------------------------------------------------- agent token log (kept when a user is deleted)
CREATE TABLE agent_runs (
    id                   {ID},
    agent_name           TEXT NOT NULL,
    user_id              BIGINT REFERENCES users(id) ON DELETE SET NULL,
    input_tokens         INTEGER NOT NULL DEFAULT 0,
    output_tokens        INTEGER NOT NULL DEFAULT 0,
    cached_tokens        INTEGER NOT NULL DEFAULT 0,
    requests             INTEGER NOT NULL DEFAULT 0,
    tool_calls           INTEGER NOT NULL DEFAULT 0,
    model                TEXT NOT NULL,
    route                TEXT NOT NULL,
    status               TEXT NOT NULL CHECK (status IN ('ok', 'error')),
    error_type           TEXT,
    duration_ms          INTEGER,
    timestamp            TEXT NOT NULL DEFAULT {NOW},
    gateway_cache_status TEXT NOT NULL DEFAULT 'unknown' CHECK (gateway_cache_status IN ('hit', 'miss', 'partial', 'unknown')),
    gateway_cache_hits   INTEGER NOT NULL DEFAULT 0,
    fresh_input_tokens   INTEGER,
    fresh_output_tokens  INTEGER
);
CREATE INDEX idx_agent_runs_agent_time ON agent_runs(agent_name, timestamp);

CREATE VIEW safety_events_report AS
SELECT s.id, s.timestamp, s.source, COALESCE(u.username::text, '(anonymous)') AS username, s.trigger_text, s.action_taken
FROM safety_events s
LEFT JOIN users u ON u.id = s.user_id
ORDER BY s.timestamp DESC, s.id DESC;
"""

TABLES = ("safety_events_report", "agent_runs", "safety_events", "measurements", "exercise_favorites", "workout_logs",
          "calendar_entries", "cardio_logs", "built_workouts", "app_meta", "goal_protocols", "exercises", "sources",
          "quiz_profiles", "quiz_questions", "users")


def statements(sql: str) -> list[str]:
    """One statement at a time (a driver may refuse several in one call). No statement here has a ; inside it."""
    return [s.strip() for s in sql.split(";\n") if s.strip() and not all(
        line.strip().startswith("--") or not line.strip() for line in s.strip().splitlines())]


def upgrade() -> None:
    for statement in statements(SCHEMA):
        op.execute(statement)


def downgrade() -> None:
    op.execute("DROP VIEW IF EXISTS safety_events_report")
    for t in TABLES[1:]:
        op.execute(f"DROP TABLE IF EXISTS {t} CASCADE")
